#!/bin/sh
# Записать значение в регистр и НЕ угробить телефон.
#
# ПОЧЕМУ ЭТО БЕЗОПАСНО: DTB на диске не меняется. Мы пишем только в
# оперативную память. Если ядро зависнет от записи - телефон сам перезагрузится
# со своим рабочим DTB. Прошивка не тронута, кирпича быть не может.
#
# $1 = адрес (hex), $2 = значение (hex)
ADDR="$1"; VAL="$2"
BEFORE=$(cat /proc/uptime | cut -d' ' -f1)
echo "WRITE $ADDR = $VAL  (uptime до: $BEFORE)"
devmem2 "0x$ADDR" 32 "0x$VAL" >/dev/null 2>&1 || echo "  devmem2 вернул ошибку"
sleep 1
echo "ВЫЖИЛ: uptime=$(cat /proc/uptime | cut -d' ' -f1)"
